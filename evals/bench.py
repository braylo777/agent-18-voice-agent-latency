"""Offline benchmark: per-stage latency, cache ablation, batching and the cost optimizer.
Usage: python3 evals/bench.py [--write]"""

import json, math, sys, time
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "src"))
sys.path.insert(0, str(root / "evals"))
from agent18.core import (
    LOADS,
    Batcher,
    Lookup,
    cost,
    make_lookup,
    route,
    run_call,
    toks,
)  # noqa: E402
from calls import make_calls  # noqa: E402

pct = lambda a, p: sorted(a)[min(len(a) - 1, math.floor(p / 100 * len(a)))]
r4 = lambda x: math.floor(x * 1e4 + 0.5) / 1e4
now = lambda: time.perf_counter() * 1000


def bench(reps=50):
    calls = make_calls()
    agg, outcomes, guard, turns = {}, {}, 0, 0
    for k in range(reps):
        lk = make_lookup()
        for c in calls:
            r = run_call(c["id"], c["u"], lk)
            turns += r["call"]["turns"]
            if k == 0:
                outcomes[r["call"]["outcome"]] = (
                    outcomes.get(r["call"]["outcome"], 0) + 1
                )
                if (
                    r["call"]["rate"]
                    and r["call"]["load"]
                    and r["call"]["rate"] > r["call"]["load"]["max"]
                ):
                    guard += 1
            for s, v in r["stages"].items():
                agg.setdefault(s, []).extend(v)
    stages = {
        s: {"p50_ms": r4(pct(v, 50)), "p95_ms": r4(pct(v, 95)), "n": len(v)}
        for s, v in agg.items()
    }

    def t(use):  # cache ablation: lookup latency with and without lane cache
        calls2 = make_calls()
        big = (
            LOADS
            + [
                {**LOADS[i % 40], "id": f"X{i}", "origin": "Nowhere ZZ"}
                for i in range(4000)
            ][::-1]
        )
        lk = Lookup(big)
        ts = []
        for _ in range(20):
            for c in calls2:
                for u in c["u"]:
                    q = {
                        "loadId": None,
                        "lane": [
                            x
                            for x in [
                                "Dallas TX",
                                "Atlanta GA",
                                "Chicago IL",
                                "Memphis TN",
                            ]
                            if x.split(" ")[0] in u
                        ],
                    }
                    if not q["lane"]:
                        continue
                    a = now()
                    lk(q, use)
                    ts.append(now() - a)
        return {"p50": pct(ts, 50), "p95": pct(ts, 95), "stats": lk.stats()}

    nc, wc = t(False), t(True)
    # optimizer: naive = every agent turn + summary generated by llama-3.1-70b, one request each.
    # optimized = router picks cheapest *measured* config meeting targets; deterministic turns use template; summaries batched x8.
    profiles = {
        "template": {
            "dialog": {
                "quality": 1,
                "p95ms": stages["negotiate"]["p95_ms"]
                + stages["tts_first_chunk"]["p95_ms"],
            },
            "summary": {"quality": 1, "p95ms": stages["summary"]["p95_ms"]},
        }
    }
    target = {"quality": 0.95, "p95ms": 800}
    naive = {"usd": 0, "requests": 0, "tin": 0, "tout": 0}
    opt = {"usd": 0, "requests": 0}
    b = Batcher(8)
    lk = make_lookup()
    SYS = "You are a freight broker agent. Load board and guardrails follow. " * 6
    for c in calls:
        r = run_call(c["id"], c["u"], lk)
        reply = "".join(r["out"])
        ti, to = toks(SYS + " ".join(c["u"])) * r["call"]["turns"], toks(reply) + toks(
            r["summary"]
        )
        naive["usd"] += cost("llama-3.1-70b-fast", ti, to)
        naive["requests"] += r["call"]["turns"] + 1
        naive["tin"] += ti
        naive["tout"] += to
        cd, cs = route("dialog", profiles, target), route("summary", profiles, target)
        opt["usd"] += cost(cd, ti, toks(reply)) + cost(
            cs, toks(r["summary"]) * 3, toks(r["summary"])
        )
        opt["requests"] += 0 if cd == "template" else r["call"]["turns"]
        b.add(c["id"])
    b.flush()
    opt["requests"] += (
        0 if route("summary", profiles, target) == "template" else b.requests
    )
    return {
        "calls": len(calls),
        "reps": reps,
        "turns_per_call": r4(turns / reps / len(calls)),
        "outcomes": outcomes,
        "guardrail_violations": guard,
        "stages": stages,
        "cache": {
            "lookup_p50_ms_nocache": r4(nc["p50"]),
            "lookup_p50_ms_cache": r4(wc["p50"]),
            "lookup_p95_ms_nocache": r4(nc["p95"]),
            "lookup_p95_ms_cache": r4(wc["p95"]),
            "hit_rate": r4(
                wc["stats"]["hits"] / (wc["stats"]["hits"] + wc["stats"]["misses"])
            ),
        },
        "batching": {
            "summary_requests_unbatched": len(calls),
            "summary_requests_batched": b.requests,
        },
        "optimizer": {
            "target": target,
            "routed": {
                "dialog": route("dialog", profiles, target),
                "summary": route("summary", profiles, target),
            },
            "naive_usd_per_call": naive["usd"] / len(calls),
            "optimized_usd_per_call": opt["usd"] / len(calls),
            "naive_model_requests": naive["requests"],
            "optimized_model_requests": opt["requests"],
            "naive_tokens_in": naive["tin"],
            "naive_tokens_out": naive["tout"],
        },
    }


if __name__ == "__main__":
    r = bench()
    p = root / "evals" / "results.json"
    old = json.loads(p.read_text()) if p.exists() else {}
    out = (
        root
        / "evals"
        / ("results.json" if "--write" in sys.argv else "results.check.json")
    )
    out.write_text(json.dumps({**old, "offline": r}, indent=1))
    print(json.dumps(r, indent=1))
